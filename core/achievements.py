"""
achievements.py — система достижений за серии выполнения.

Каждое достижение — это порог серии, при достижении которого
показывается поздравление.
"""

# Пороги серии: {дней: (эмодзи, название, описание)}
ACHIEVEMENTS = {
    3:  ("🌱", "Первые шаги",     "3 дня подряд — хорошее начало!"),
    7:  ("🔥", "Неделя силы",     "7 дней подряд — ты в ударе!"),
    14: ("💪", "Две недели",      "14 дней подряд — железная дисциплина!"),
    30: ("🏆", "Месяц!",          "30 дней подряд — это уровень мастерства!"),
    100: ("👑", "Легенда",        "100 дней подряд — невероятно!"),
}


def check_achievement(streak):
    """
    Проверяет, достиг ли streak какого-то порога.
    Возвращает (эмодзи, название, описание) или None.
    """
    if streak in ACHIEVEMENTS:
        return ACHIEVEMENTS[streak]
    return None